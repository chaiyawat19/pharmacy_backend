/**
 * ระดับความคิดเห็นจากค่าเฉลี่ย — เกณฑ์ของ Best (1977) ที่ใช้ทั่วไปในงานวิจัยไทย
 * 4.51–5.00 มากที่สุด, 3.51–4.50 มาก, 2.51–3.50 ปานกลาง, 1.51–2.50 น้อย, 1.00–1.50 น้อยที่สุด
 */
export function interpretMean(mean: number): string {
  if (mean >= 4.51) return 'มากที่สุด';
  if (mean >= 3.51) return 'มาก';
  if (mean >= 2.51) return 'ปานกลาง';
  if (mean >= 1.51) return 'น้อย';
  return 'น้อยที่สุด';
}
